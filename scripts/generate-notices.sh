#!/usr/bin/env bash
# Regenerates THIRD_PARTY_NOTICES (repo root), ui/public/third-party-notices.txt and the same list
# as structured data for the About window, ui/public/third-party-notices.json (scripts/notices.js).
# CI runs it for every release before bundling and on main after dependency changes
# (.github/workflows/notices.yml), so running it by hand is optional. Needs: cargo-about at the version in
# scripts/license-tools.env, node/npm, and an installed node_modules (npm ci).
#
# Licence policy: fails when a dependency has a licence that is not allowed, so an incompatible
# dependency is noticed at once. Rust crates are checked against `accepted` in about.toml, npm
# packages against npm_allowed below (applied by scripts/notices.js). Mumcord is AGPL-3.0-only;
# only permissive or weak-copyleft licences compatible with it belong on either list.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"
# shellcheck source=scripts/license-tools.env
source scripts/license-tools.env

# Production npm packages, as SPDX identifiers. OFL-1.1 covers the bundled fonts.
npm_allowed="MIT Apache-2.0 BSD-2-Clause BSD-3-Clause ISC 0BSD MPL-2.0 CC0-1.0 Unlicense Zlib OFL-1.1"

command -v cargo-about >/dev/null 2>&1 || PATH="$HOME/.cargo/bin:$PATH"
command -v cargo-about >/dev/null 2>&1 || {
  echo "cargo-about not found. Install: cargo install cargo-about --version $CARGO_ABOUT_VERSION --locked --features cli" >&2
  exit 1
}
installed="$(cargo about --version | awk '{print $2}')"
if [ "$installed" != "$CARGO_ABOUT_VERSION" ]; then
  echo "warning: cargo-about $installed is installed, CI uses $CARGO_ABOUT_VERSION; the output may differ." >&2
fi
[ -d node_modules ] || { echo "node_modules missing. Run: npm ci" >&2; exit 1; }
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

cargo about generate --locked --format json > "$tmp/rust.json" || {
  echo "error: cargo-about failed. If it reports 'failed to satisfy license requirements', a Rust" >&2
  echo "dependency uses a licence that is not in 'accepted' in about.toml. Replace the dependency," >&2
  echo "or add the licence there only after checking that it is compatible with the AGPL-3.0." >&2
  exit 1
}
npx --yes "license-checker-rseidelsohn@$LICENSE_CHECKER_VERSION" --production --json > "$tmp/npm.json"
cargo metadata --locked --format-version 1 > "$tmp/metadata.json"

# One list of components feeds both outputs: the JSON for the About window and the plain-text
# sections below. It also applies the npm licence policy.
node scripts/notices.js --root "$root" --rust "$tmp/rust.json" --npm "$tmp/npm.json" \
  --metadata "$tmp/metadata.json" --npm-allowed "$npm_allowed" --out "$tmp"

{
  cat <<'HEAD'
Mumcord - Third-party notices
=============================

Mumcord itself is licensed under the GNU AGPL v3 only (see the LICENSE and NOTICE files).
It includes or links the third-party components listed below. This file is
generated by scripts/generate-notices.sh; do not edit it by hand.

HEAD
  # Components that are not Rust or npm packages come from licenses/native.json.
  cat <<'NATIVE'
BUNDLED COMPONENTS (not Rust or npm packages)
=============================================

The Mumble protocol definitions, and the C/C++ libraries that Mumcord compiles in,
links or loads: libopus and SQLite are compiled in by Rust crates, libvpx is
statically linked into every build, PipeWire is loaded from the Linux system, and
the Linux AppImage carries GStreamer and WebKitGTK from its Ubuntu 24.04 build host.
BoringSSL-derived code compiled in by the ring crate is covered by ring's license
texts in the Rust section below.

NATIVE
  cat "$tmp/native.txt"
  cat <<'SYSTEM'
OTHER LINUX SYSTEM LIBRARIES
============================

Other system libraries bundled in the AppImage by linuxdeploy (taken from the
Ubuntu 24.04 build system), under their own licences, mostly LGPL, MIT, BSD or
similar permissive terms:
  GTK 3, GLib/GIO/GObject, Pango, Cairo, GdkPixbuf, ATK, librsvg, libsoup 3,
  libayatana-appindicator, libdbusmenu, ICU, libxml2, libxslt, GnuTLS, Nettle,
  libsecret, libnice, libsrtp2, libwebp, libjpeg, libpng, libtiff, libsqlite3,
  libopus, libvorbis, libogg, libFLAC, libmpg123, libmp3lame, libsndfile,
  libpulse, libX11 and the other X.Org client libraries, and their dependencies.
  The exact list is the content of usr/lib inside the AppImage
  (run the AppImage with --appimage-extract to list it). Each library's licence
  is in the Debian copyright file of the source package of the same name:
  https://copyright.ubuntu.com/ or /usr/share/doc/<package>/copyright.

SOURCE CODE OFFER (LGPL and GPL components)
-------------------------------------------

Several libraries above (GStreamer, WebKitGTK, GTK, GLib, and others) are licensed
under the GNU LGPL or GPL. You may replace them with your own build: the AppImage
loads them as separate shared libraries. The corresponding source code of the exact
versions in a Mumcord release is the source of the Ubuntu 24.04 packages used to
build that release, available with "apt source <package>" on Ubuntu 24.04 or from
  https://archive.ubuntu.com/ubuntu/pool/ and https://launchpad.net/ubuntu
Upstream releases:
  GStreamer   https://gstreamer.freedesktop.org/src/
  WebKitGTK   https://webkitgtk.org/releases/
  GTK, GLib   https://download.gnome.org/sources/
  libvpx      https://github.com/webmproject/libvpx/releases
  PipeWire    https://gitlab.freedesktop.org/pipewire/pipewire/-/tags
We also provide the source code of any of these components on request, for at
least three years after the release that contained it: open an issue at
https://github.com/Mumcord/mumcord/issues or write to the maintainer.
Mumcord's own source code is licensed under the GNU AGPL v3 and is available at
https://github.com/Mumcord/mumcord.


SYSTEM
  cat "$tmp/rust.txt"
  printf '\n\n'
  cat "$tmp/npm.txt"
} | tr -d '\r' > THIRD_PARTY_NOTICES

mkdir -p ui/public
cp THIRD_PARTY_NOTICES ui/public/third-party-notices.txt
cp "$tmp/third-party-notices.json" ui/public/third-party-notices.json
echo "Wrote THIRD_PARTY_NOTICES, ui/public/third-party-notices.txt ($(wc -l < THIRD_PARTY_NOTICES) lines) and ui/public/third-party-notices.json"
