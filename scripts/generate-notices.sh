#!/usr/bin/env bash
# Regenerates THIRD_PARTY_NOTICES (repo root) and ui/public/third-party-notices.txt.
# Run after dependencies change. Needs: cargo-about (cargo install cargo-about --locked --features cli),
# node/npm, and an installed node_modules (npm ci).
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"

command -v cargo-about >/dev/null 2>&1 || PATH="$HOME/.cargo/bin:$PATH"
command -v cargo-about >/dev/null 2>&1 || {
  echo "cargo-about not found. Install: cargo install cargo-about --locked --features cli" >&2
  exit 1
}
[ -d node_modules ] || { echo "node_modules missing. Run: npm ci" >&2; exit 1; }

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

cargo about generate about.hbs > "$tmp/rust.txt"
npx --yes license-checker-rseidelsohn --production --json > "$tmp/npm.json"

node - "$tmp/npm.json" > "$tmp/npm.txt" <<'NODE'
const fs = require("fs");
const data = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const bar = "-".repeat(80);
const out = ["NPM DEPENDENCIES (production)", "=============================", ""];
for (const key of Object.keys(data).sort()) {
  const d = data[key];
  if (key.startsWith("mumcord@")) continue;
  out.push(bar, key, bar, "", `License: ${d.licenses}`);
  if (d.repository) out.push(`Repository: ${d.repository}`);
  if (d.publisher) out.push(`Publisher: ${d.publisher}`);
  out.push("");
  let text = "";
  const f = d.licenseFile;
  if (f && fs.existsSync(f) && !/readme/i.test(f)) text = fs.readFileSync(f, "utf8").trim();
  out.push(text || "(No license file shipped with this package; see the license identifier above.)", "");
}
process.stdout.write(out.join("\n") + "\n");
NODE

{
  cat <<'HEAD'
Mumcord - Third-party notices
=============================

Mumcord itself is licensed under the MIT License (see the LICENSE file).
It includes or links the third-party components listed below. This file is
generated by scripts/generate-notices.sh; do not edit it by hand.

HEAD
  cat <<'MUMBLE'
MUMBLE (BSD 3-Clause) - protocol definitions
============================================

The protocol definition files in proto/ (Mumble.proto, MumbleUDP.proto) are
taken from the Mumble project and are used under its BSD license:

MUMBLE
  cat proto/LICENSE.mumble
  cat <<'PLUGINS'


MUMBLE GAME PLUGINS
===================

The official Mumble game plugins that Mumcord can load at runtime to read
game positions are developed by the Mumble project and are licensed under
the same BSD license shown above. They are not part of this repository.
Mumcord is compatible with Mumble but is not affiliated with or endorsed by
the Mumble project.


PLUGINS
  cat "$tmp/rust.txt"
  printf '\n\n'
  cat "$tmp/npm.txt"
} > THIRD_PARTY_NOTICES

mkdir -p ui/public
cp THIRD_PARTY_NOTICES ui/public/third-party-notices.txt
echo "Wrote THIRD_PARTY_NOTICES and ui/public/third-party-notices.txt ($(wc -l < THIRD_PARTY_NOTICES) lines)"
